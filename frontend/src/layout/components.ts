/**
 * 组件能力目录（M1）。
 *
 * 目录从「最低尺寸表」升级为「组件能力目录」：每种组件都登记类别、尺寸、滚动归属、
 * grow/reflow 能力、默认状态占位和可配置能力说明。校验器以这里作为唯一组件登记源。
 */
import type { ComponentCategory, ComponentKind, ComponentState, ComponentStateStrategy, ScrollOwnership } from './schema'

export interface ComponentMeta {
  kind: ComponentKind
  category: ComponentCategory
  label: string
  description: string
  /** 业务最低宽（px）：低于它该组件被压到不可读/不可用。 */
  minW: number
  /** 业务最低高（px）。 */
  minH: number
  /** 理想宽高（渲染参考，不作为硬下限）。 */
  idealW?: number
  idealH?: number
  maxW?: number
  maxH?: number
  /** 默认滚动归属（slot 未显式声明时取此）。 */
  defaultScroll: ScrollOwnership
  /** 能否作为吃富余空间的「主表/主图」（规范 §1 放置规则 3）。 */
  canGrowMain: boolean
  /** 是否无强阅读顺序、可参与重排多列（规范 §5 条件 2/3）。 */
  reflowable: boolean
  /** 状态切换默认占位策略，页面可在 slot.states 中收紧。 */
  defaultStates: Partial<Record<ComponentState, ComponentStateStrategy>>
  /** 专属配置能力摘要；真实类型校验在 componentSchemas.ts。 */
  configCapabilities: string[]
}

type MetaInput = Omit<ComponentMeta, 'kind' | 'defaultStates'> & {
  defaultStates?: Partial<Record<ComponentState, ComponentStateStrategy>>
}

const DEFAULT_STATES: Partial<Record<ComponentState, ComponentStateStrategy>> = {
  loading: { reserveSpace: true },
  empty: { reserveSpace: true },
  error: { reserveSpace: true },
}

function meta(kind: ComponentKind, input: MetaInput): ComponentMeta {
  const { defaultStates, ...rest } = input
  return {
    kind,
    ...rest,
    // 专属状态只收紧自己的占位高度，不能覆盖掉所有组件共有的 loading / empty / error 策略。
    defaultStates: { ...DEFAULT_STATES, ...defaultStates },
  }
}

